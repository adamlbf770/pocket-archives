import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

let snapshot = { schemaVersion: 1, batchId: "No batch loaded", createdAt: null, publishMode: "DRAFT_ONLY", summary: { AUTO_DRAFT: 0, REVIEW: 0, RESCAN: 0, CONFLICT: 0 }, cards: [] };
try { snapshot = JSON.parse(await readFile(resolve("outputs/ingestion/latest.json"), "utf8")); } catch {}
const safe = {
  ...snapshot,
  cards: snapshot.cards.map((card) => ({
    sku: card.sku,
    guess: card.guess,
    externalMatch: card.externalMatch ? { source: card.externalMatch.source, externalId: card.externalMatch.externalId, identity: card.externalMatch.identity, reason: card.externalMatch.reason, error: card.externalMatch.error } : null,
    orientation: card.front?.orientation,
    quality: { reasons: card.quality?.reasons ?? [], rescanRequired: Boolean(card.quality?.rescanRequired) },
    duplicateOf: card.duplicateOf,
    confidence: card.confidence,
  })),
};
const target = resolve("app/ingestion/ingestion.generated.ts");
await mkdir(dirname(target), { recursive: true });
await writeFile(target, `// Generated by scripts/sync-ingestion-dashboard.mjs.\nexport const ingestionSnapshot = ${JSON.stringify(safe, null, 2)} as const;\n`);
console.log(`Ingestion dashboard synced: ${safe.cards.length} cards from ${safe.batchId}.`);
